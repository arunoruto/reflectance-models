_LUT_Y = jnp.concatenate(((1473.0 - _POINTS[:, 1]) / (1473.0 - 199.0), jnp.array([(1473.0 - 1394.0) / (1473.0 - 199.0)])))


def lunar_lambert(
    rho: jax.Array,
    th_i: jax.Array,
    th_e: jax.Array,
    alpha: jax.Array,
) -> jax.Array:
    r"""MATLAB-compatible lunar-Lambert reflectance model.

    This ports the reference ``lunar_lambert_model.m``. It is a lookup-table
    model, tabulated for :math:`\bar{\theta} = 10^\circ` and :math:`w = 0.1`,
    and is intentionally separate from physical Lambertian reflectance
    (:func:`~refmod.lambert.lambert`).
    """
    rho = jnp.asarray(rho)
    th_i = jnp.asarray(th_i)
    th_e = jnp.asarray(th_e)
    alpha = jnp.asarray(alpha)

    alpha_deg = alpha / jnp.pi * 180.0
    l_value = jnp.interp(alpha_deg, _LUT_X, _LUT_Y, left=jnp.nan, right=jnp.nan)
    cos_i = jnp.cos(th_i)
    cos_e = jnp.cos(th_e)
    return rho * (2.0 * l_value * cos_i / (cos_i + cos_e) + (1.0 - l_value) * cos_i)
